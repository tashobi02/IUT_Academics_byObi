DROP TABLE VEHICLE; 
DROP TABLE OWNER; 

CREATE TABLE VEHICLE (
    VEHICLE_ID INT,
    MODEL VARCHAR2(50),
    MTYPE VARCHAR2(20),
    HORSEPOWER INT,
    TORQUE INT,
    WEIGHT INT,
    SPEED INT,
    CONSTRAINT VEHICLE_ID_PK PRIMARY KEY (VEHICLE_ID)
);
CREATE TABLE OWNER (
    OWNER_ID INT,
    FIRST_NAME VARCHAR2(30),
    LAST_NAME VARCHAR2(30),
    CITY VARCHAR2(30), 
    CONSTRAINT OWNER_ID_PK PRIMARY KEY (OWNER_ID) 
);
