FROM OWNER O1
JOIN VEHICLE V ON O1.OWNER_ID = V.VEHICLE_ID
JOIN OWNER O2 ON O1.OWNER_ID != O2.OWNER_ID AND O2.OWNER_ID = V.VEHICLE_ID
ORDER BY V.MODEL;

