SELECT AVG (HORSEPOWER)
FROM VEHICLE; 

SELECT MTYPE, AVG_HORSEPOWER
FROM (
    SELECT MTYPE, AVG(HORSEPOWER) AS AVG_HORSEPOWER
    FROM VEHICLE
    GROUP BY MTYPE
    ORDER BY AVG_HORSEPOWER DESC
) 
WHERE ROWNUM = 1;

SELECT MTYPE
FROM (
    SELECT MTYPE, COUNT(*) AS CAR_COUNT
    FROM VEHICLE
    GROUP BY MTYPE
    ORDER BY CAR_COUNT DESC
)
WHERE ROWNUM = 1;


SELECT MODEL, MTYPE, WEIGHT
FROM VEHICLE
